-- SQL Editor -> New query -> pegar -> Run -> Export -> Copy as JSON.
-- Genera, en orden, el SQL para recrear la base de datos: tipos, tablas,
-- llaves foraneas, indices, vistas, funciones, triggers, RLS, reglas y
-- permisos. Los webhooks (push_pedidos, push_mensajes) se omiten a proposito
-- porque su definicion incluye el secreto WEBHOOK_SECRET.
-- ============================================================================
with
tabs as (
  select c.oid, c.relname
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'p')
),
tipos as (
  select 1 as orden, t.typname::text as nombre,
         'create type public.' || quote_ident(t.typname) || ' as enum ('
           || string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) || ');' as sql
  from pg_type t
  join pg_namespace n on n.oid = t.typnamespace
  join pg_enum e on e.enumtypid = t.oid
  where n.nspname = 'public'
  group by t.typname
),
columnas as (
  select t.relname,
         string_agg(
           '  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
             || case a.attidentity
                  when 'a' then ' generated always as identity'
                  when 'd' then ' generated by default as identity'
                  else '' end
             || case
                  when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
                  when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid)
                  else '' end
             || case when a.attnotnull then ' not null' else '' end,
           E',\n' order by a.attnum) as cuerpo
  from tabs t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = t.oid and d.adnum = a.attnum
  group by t.relname
),
restricciones as (
  select t.relname,
         string_agg('  constraint ' || quote_ident(con.conname) || ' ' || pg_get_constraintdef(con.oid),
                    E',\n' order by con.contype desc, con.conname) as cuerpo
  from tabs t
  join pg_constraint con on con.conrelid = t.oid and con.contype in ('p', 'u', 'c', 'x')
  group by t.relname
),
tablas as (
  select 2 as orden, c.relname::text as nombre,
         'create table public.' || quote_ident(c.relname) || E' (\n' || c.cuerpo
           || coalesce(E',\n' || r.cuerpo, '') || E'\n);' as sql
  from columnas c
  left join restricciones r on r.relname = c.relname
),
llaves as (
  select 3 as orden, t.relname || '.' || con.conname as nombre,
         'alter table public.' || quote_ident(t.relname) || ' add constraint ' || quote_ident(con.conname)
           || ' ' || pg_get_constraintdef(con.oid) || ';' as sql
  from tabs t
  join pg_constraint con on con.conrelid = t.oid and con.contype = 'f'
),
indices as (
  select 4 as orden, i.indexname::text as nombre, i.indexdef || ';' as sql
  from pg_indexes i
  where i.schemaname = 'public'
    and not exists (
      select 1 from pg_constraint con
      join pg_class ic on ic.oid = con.conindid
      where ic.relname = i.indexname
    )
),
vistas as (
  select 5 as orden, v.viewname::text as nombre,
         'create or replace view public.' || quote_ident(v.viewname) || E' as\n' || v.definition as sql
  from pg_views v
  where v.schemaname = 'public'
),
funciones as (
  select 6 as orden, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')' as nombre,
         pg_get_functiondef(p.oid) || ';' as sql
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public'
    and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend dep where dep.objid = p.oid and dep.deptype = 'e')
),
disparadores as (
  select 7 as orden, t.relname || '.' || tg.tgname as nombre,
         pg_get_triggerdef(tg.oid) || ';' as sql
  from pg_trigger tg
  join tabs t on t.oid = tg.tgrelid
  where not tg.tgisinternal
    and pg_get_triggerdef(tg.oid) not ilike '%http_request%'
),
disparadores_auth as (
  -- p. ej. el que crea el perfil cuando alguien se registra (handle_new_user)
  select 7 as orden, 'auth.' || c.relname || '.' || tg.tgname as nombre,
         pg_get_triggerdef(tg.oid) || ';' as sql
  from pg_trigger tg
  join pg_class c on c.oid = tg.tgrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'auth' and not tg.tgisinternal
),
rls as (
  select 8 as orden, c.relname::text as nombre,
         'alter table public.' || quote_ident(c.relname) || ' enable row level security;' as sql
  from pg_class c
  join tabs t on t.oid = c.oid
  where c.relrowsecurity
),
reglas as (
  select 9 as orden, p.schemaname || '.' || p.tablename || '.' || p.policyname as nombre,
         'create policy ' || quote_ident(p.policyname) || ' on ' || p.schemaname || '.' || quote_ident(p.tablename)
           || ' as ' || lower(p.permissive) || ' for ' || lower(p.cmd)
           || ' to ' || array_to_string(p.roles, ', ')
           || coalesce(' using (' || p.qual || ')', '')
           || coalesce(' with check (' || p.with_check || ')', '') || ';' as sql
  from pg_policies p
  where p.schemaname in ('public', 'storage')
),
carpetas as (
  -- carpetas de Storage (fotos de productos, logos…)
  select 12 as orden, b.id::text as nombre,
         'insert into storage.buckets (id, name, public) values ('
           || quote_literal(b.id) || ', ' || quote_literal(b.name) || ', ' || b.public::text
           || ') on conflict (id) do nothing;' as sql
  from storage.buckets b
),
permisos as (
  select 10 as orden, g.table_name || '.' || g.grantee as nombre,
         'grant ' || string_agg(lower(g.privilege_type), ', ' order by g.privilege_type)
           || ' on public.' || quote_ident(g.table_name) || ' to ' || g.grantee || ';' as sql
  from information_schema.role_table_grants g
  where g.table_schema = 'public' and g.grantee in ('anon', 'authenticated', 'service_role')
  group by g.table_name, g.grantee
),
webhooks as (
  select 11 as orden, t.relname || '.' || tg.tgname as nombre,
         '-- Webhook ' || tg.tgname || ' en public.' || t.relname
           || ': se crea desde Integrations > Database Webhooks (ver supabase/functions/send-push/README.md)' as sql
  from pg_trigger tg
  join tabs t on t.oid = tg.tgrelid
  where not tg.tgisinternal
    and pg_get_triggerdef(tg.oid) ilike '%http_request%'
)
select orden, nombre, sql from (
  select * from tipos
  union all select * from tablas
  union all select * from llaves
  union all select * from indices
  union all select * from vistas
  union all select * from funciones
  union all select * from disparadores
  union all select * from disparadores_auth
  union all select * from rls
  union all select * from reglas
  union all select * from permisos
  union all select * from webhooks
  union all select * from carpetas
) todo
order by orden, nombre;
